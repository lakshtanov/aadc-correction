"""
example_barrier_hw_ql.py — Greeks of a down-and-out call with stochastic rates, the model taken from QuantLib.

The paths are generated by QuantLib's own processes recorded on the AADC tape (AADC build of QuantLib:
pip install aadc-quantlib-tracing, in a separate environment -- it pins its own aadc version):
  spot   ql.BlackScholesMertonProcess (zero rates; the short rate of the Hull-White process is added to the drift)
  rate   ql.HullWhiteProcess (a = 0.1, sigma_r = 0.01, flat curve 5%), correlation rho = -0.3 with the spot
Product: S0 = 100, K = 90, barrier B = 80 observed on 50 dates, T = 1, payoff 1{alive} exp(-int r) (S_T - K)^+.
The QuantLib process receives the normals as tape inputs (process.evolve(t, x, dt, dw)); the correction driver
finds the 50 barrier comparisons on the tape by itself.

Greeks dV/dS0, dV/dsigma, dV/dsigma_r by
  correction + MC          CorrectionDriverVec2
  correction + Sobol (B)   CorrectionDriverRQMC: scrambled Sobol rotated from the tape gradients on 512 pilot paths --
                           no knowledge of how QuantLib lays out its normals is needed
against a central bump with common random numbers (2M paths).
Usage: OPENBLAS_NUM_THREADS=1 python examples/example_barrier_hw_ql.py      (THREADS=10, R=8, N=16384; R=32: Sobol reduces the error 5.1x, Greeks within 2 s.e. of MC and of the bump)
"""
import sys, os, io, math, time, contextlib
import numpy as np
import aadc
sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from correction_driver_vec2 import CorrectionDriverVec2
from rqmc import CorrectionDriverRQMC
try:
    import aadc_quantlib_tracing as ql
except ImportError:
    print("needs the AADC build of QuantLib: pip install aadc-quantlib-tracing"); sys.exit(0)

THREADS, R, N = int(os.environ.get("THREADS", "10")), int(os.environ.get("R", "8")), int(os.environ.get("N", "16384"))
S0, K, B, SIG, R0, A_HW, SIG_R, RHO, T, NSTEP = 100.0, 90.0, 80.0, 0.25, 0.05, 0.1, 0.01, -0.3, 1.0, 50
TODAY = ql.Date(20, 11, 2026); ql.Settings.instance().evaluationDate = TODAY
DC = ql.Actual365Fixed()
c = aadc.idouble
print(f"QuantLib {ql.__version__}, aadc {aadc.__version__}")


def flat(r):
    return ql.YieldTermStructureHandle(ql.FlatForward(TODAY, r, DC))


# ── record: QuantLib processes on the AADC tape ──────────────────────────────────────────────────
fn = aadc.Functions(); fn.start_recording(register_switches=aadc.SWITCH_JUMP)
s0 = c(S0); a_s = s0.mark_as_input()
vol = c(SIG); a_v = vol.mark_as_input()
sr = c(SIG_R); a_r = sr.mark_as_input()
bsm = ql.BlackScholesMertonProcess(ql.QuoteHandle(ql.SimpleQuote(s0)), flat(0.0), flat(0.0),
                                   ql.BlackVolTermStructureHandle(ql.BlackConstantVol(TODAY, ql.NullCalendar(), ql.QuoteHandle(ql.SimpleQuote(vol)), DC)))
hw = ql.HullWhiteProcess(flat(R0), A_HW, sr)
dt = T / NSTEP
z = [c(0.0) for _ in range(2 * NSTEP)]; za = [q.mark_as_input() for q in z]
S, r, D, alive = bsm.x0(), hw.x0(), c(0.0), c(1.0)
for k in range(NSTEP):
    zs = z[2 * k]; zr = c(RHO) * z[2 * k] + c(math.sqrt(1 - RHO * RHO)) * z[2 * k + 1]
    S = bsm.evolve(k * dt, S, dt, zs) * aadc.math.exp(r * c(dt))      # GBM step of QuantLib + short-rate drift
    D = D + r * c(dt)
    r = hw.evolve(k * dt, r, dt, zr)
    alive = alive * aadc.iif(S > c(B), c(1.0), c(0.0))                 # the barrier: found by the driver on the tape
rP = (alive * aadc.math.exp(-D) * aadc.math.max(S - c(K), c(0.0))).mark_as_output()
fn.stop_recording()
th, names = [a_s, a_v, a_r], ["dV/dS0", "dV/dsigma", "dV/dsigma_r"]
thv = {a_s: S0, a_v: SIG, a_r: SIG_R}

# ── correction: MC and Sobol (option B) ──────────────────────────────────────────────────────────
drv = CorrectionDriverVec2(fn, rP, za, th, num_threads=THREADS)
q = CorrectionDriverRQMC(fn, rP, za, th, num_threads=THREADS, n_pilot=512, pilot_seed=999)
with contextlib.redirect_stdout(io.StringIO()):
    drv.precompute_directions(thv); q.precompute_directions(thv)
print(f"tape: {len(za)} normals, {drv.n_ind} comparisons found on the tape; Sobol rotation from 512 pilot paths in {q.rotation_time:.2f}s")
res = {}
for src in ("MC", "Sobol"):
    est, tm = [], 0.0
    for rr in range(R):
        Z = np.random.default_rng(100 + rr).standard_normal((N, len(za))) if src == "MC" else q.sample(N, rr)
        t0 = time.perf_counter()
        with contextlib.redirect_stdout(io.StringIO()):
            est.append(np.asarray(drv.run(Z)["total"]))
        tm += time.perf_counter() - t0
    res[src] = (np.array(est), tm / R)

# ── reference: central bump with common random numbers ───────────────────────────────────────────
H = [0.5, 0.0025, 0.0005]; rng = np.random.default_rng(20261120); s1 = np.zeros(3); s2 = np.zeros(3); n = 0
while n < 2_000_000:
    Zb = rng.standard_normal((250_000, len(za))); base = {a: np.ascontiguousarray(Zb[:, j]) for j, a in enumerate(za)}
    for k, a in enumerate(th):
        v = []
        for sg in (1, -1):
            inp = dict(base); inp.update(thv); inp[a] = thv[a] + sg * H[k]
            v.append(np.asarray(aadc.evaluate(funcs=fn, request={rP: []}, inputs=inp, workers=THREADS)[0][rP]))
        g = (v[0] - v[1]) / (2 * H[k]); s1[k] += g.sum(); s2[k] += (g * g).sum()
    n += len(Zb)
ref = s1 / n; ref_se = np.sqrt((s2 / n - ref * ref) / n)

print(f"\nDown-and-out call, GBM (BlackScholesMertonProcess) + HullWhiteProcess, {NSTEP} dates; {R} x {N} paths")
print(f"{'Greek':13s} {'correction + MC':>24s} {'correction + Sobol (B)':>24s} {'CRN bump, 2M paths':>22s}")
for k, nm in enumerate(names):
    a, b = res["MC"][0][:, k], res["Sobol"][0][:, k]
    print(f"{nm:13s} {a.mean():+12.5f} ± {a.std(ddof=1)/math.sqrt(R):.5f} {b.mean():+12.5f} ± {b.std(ddof=1)/math.sqrt(R):.5f} "
          f"{ref[k]:+12.5f} ± {ref_se[k]:.5f}")
print(f"time per estimate: MC {res['MC'][1]:.2f}s, Sobol {res['Sobol'][1]:.2f}s (+ {q.rotation_time:.2f}s once for the rotation); "
      f"Sobol reduces the error {np.mean(res['MC'][0].std(0, ddof=1) / res['Sobol'][0].std(0, ddof=1)):.1f}x on average")
